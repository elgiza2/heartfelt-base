/** Generates src/lib/apiApps/publicApis.generated.ts
 *
 *  Source: the public-apis/public-apis repository (the community-curated index
 *  of public APIs, grouped by category with the auth type for each service).
 *  Each entry is matched against the APIs.guru OpenAPI index by domain, so the
 *  ones that ship a machine-readable description can be opened and used with
 *  nothing but the user's API key.
 *
 *  Run: bun scripts/gen-public-apis.mjs
 */
import { writeFileSync } from "node:fs";

const README =
  "https://raw.githubusercontent.com/public-apis/public-apis/master/README.md";
const GURU = "https://api.apis.guru/v2/list.json";

const md = await (await fetch(README)).text();
const guru = await (await fetch(GURU)).json();

/** domain -> guru key (prefer the shortest, i.e. the flagship API). */
const byDomain = new Map();
for (const key of Object.keys(guru)) {
  const domain = key.split(":")[0].toLowerCase();
  const current = byDomain.get(domain);
  if (!current || key.length < current.length) byDomain.set(domain, key);
}

function host(url) {
  try {
    return new URL(url).hostname.toLowerCase().replace(/^www\./, "");
  } catch {
    return "";
  }
}

function rootDomain(h) {
  const parts = h.split(".");
  return parts.slice(-2).join(".");
}

/** Doc hosts that say nothing about which service an entry belongs to. */
const GENERIC_HOSTS = [
  "github.com",
  "github.io",
  "gitlab.com",
  "gitlab.io",
  "readthedocs.io",
  "readthedocs.org",
  "netlify.app",
  "vercel.app",
  "gitbook.io",
  "gitbook.com",
  "herokuapp.com",
  "rapidapi.com",
  "getpostman.com",
  "postman.com",
  "google.com",
  "notion.site",
  "docs.rs",
  "apache.org",
  "wordpress.com",
  "medium.com",
  "pages.dev",
  "surge.sh",
  "firebaseapp.com",
  "web.app",
  "azurewebsites.net",
];

function guruKeyFor(url) {
  const h = host(url);
  const root = rootDomain(h);
  if (GENERIC_HOSTS.includes(h) || GENERIC_HOSTS.includes(root)) return null;
  return byDomain.get(h) ?? byDomain.get(root) ?? null;
}

const sections = md.split(/^### /m).slice(1);
const rows = [];
const seen = new Set();

for (const section of sections) {
  const lines = section.split("\n");
  const category = lines[0].trim();
  if (!category || category.startsWith("Index")) continue;
  for (const line of lines) {
    const m = line.match(/^\|\s*\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)\s*\|([^|]*)\|([^|]*)\|/);
    if (!m) continue;
    const [, name, rawUrl, description, auth] = m;
    const url = rawUrl.split("?")[0];
    const key = name.trim().toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    rows.push({
      name: name.trim(),
      category,
      description: description.trim().replace(/\s+/g, " "),
      docsUrl: url,
      auth: auth.replace(/`/g, "").trim() || "No",
      guruKey: guruKeyFor(url),
    });
  }
}

const withSpec = rows.filter((r) => r.guruKey);

const body = `// AUTO-GENERATED by scripts/gen-public-apis.mjs — do not edit by hand.
// Source: github.com/public-apis/public-apis (community-curated index of public
// APIs), cross-referenced with the APIs.guru OpenAPI index so each entry can be
// opened, read from its own specification, and used with the user's API key.

export type PublicApiEntry = {
  /** Directory id (\`dir:<apis.guru key>\`) when a specification exists. */
  id: string | null;
  name: string;
  category: string;
  description: string;
  docsUrl: string;
  /** Auth style as documented by the source list. */
  auth: string;
};

/** Curated list, in source order (most recognised services per category). */
export const publicApis: PublicApiEntry[] = ${JSON.stringify(
  rows.map((r) => ({
    id: r.guruKey ? `dir:${r.guruKey}` : null,
    name: r.name,
    category: r.category,
    description: r.description,
    docsUrl: r.docsUrl,
    auth: r.auth,
  })),
  null,
  2,
)};

/** Ids of curated entries that ship an OpenAPI description, in curated order. */
export const publicApiIds: string[] = ${JSON.stringify(
  withSpec.map((r) => `dir:${r.guruKey}`),
  null,
  2,
)};
`;

writeFileSync("src/lib/apiApps/publicApis.generated.ts", body);
console.log(`entries: ${rows.length}, with OpenAPI spec: ${withSpec.length}`);
